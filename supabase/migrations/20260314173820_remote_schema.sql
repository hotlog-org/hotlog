DO $baseline$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname = ANY (ARRAY[
        'api_keys', 'components', 'events', 'fields', 'layouts', 'permissions',
        'projects', 'role_permissions', 'roles', 'schemas', 'user_projects',
        'user_roles', 'role_layouts', 'invitations'
      ])
  ) THEN
    RAISE EXCEPTION 'Prerequisite baseline requires an empty Hotlog schema; never replay on an existing/linked project'
      USING ERRCODE = '55000';
  END IF;
END;
$baseline$;

